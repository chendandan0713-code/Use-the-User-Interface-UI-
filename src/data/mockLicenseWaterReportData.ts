// ==================== 3. 证照年度数据支撑汇总计算工具函数 ====================
export function generateLicenseAnnualSummary(
  licenses: WaterPermitLicenseDimension[],
  reports: LicenseMonthlyWaterReport[],
  year: number
): LicenseAnnualSupportSummary[] {
  return licenses.map((lic) => {
    // 筛选当前证照在指定年份下的月度报表
    const licReports = reports.filter((r) => r.licenseId === lic.id && r.year === year);

    let totalApprovedWater = 0;
    let totalPendingWater = 0;
    let totalDraftWater = 0;
    let surfaceWaterTotal = 0;
    let groundwaterTotal = 0;
    let unconventionalTotal = 0;

    let reportedMonthsCount = 0;
    let approvedMonthsCount = 0;

    // 构建 1 至 12 月份的数据明细数组
    const monthlyBreakdown = Array.from({ length: 12 }, (_, i) => {
      const month = i + 1;
      const monthLabel = `${month}月`;
      const rep = licReports.find((r) => r.month === month);

      if (rep) {
        reportedMonthsCount++;
        if (rep.status === 'approved') {
          approvedMonthsCount++;
          totalApprovedWater += rep.totalWater;
          surfaceWaterTotal += rep.surfaceWater;
          groundwaterTotal += rep.groundwater;
          unconventionalTotal += rep.unconventionalWater;
        } else if (rep.status === 'pending_city') {
          totalPendingWater += rep.totalWater;
        } else if (rep.status === 'draft') {
          totalDraftWater += rep.totalWater;
        }

        return {
          month,
          monthLabel,
          surfaceWater: rep.surfaceWater,
          groundwater: rep.groundwater,
          unconventionalWater: rep.unconventionalWater,
          totalWater: rep.totalWater,
          status: rep.status,
          reportId: rep.id,
          isSupported: rep.status === 'approved',
        };
      }

      return {
        month,
        monthLabel,
        surfaceWater: 0,
        groundwater: 0,
        unconventionalWater: 0,
        totalWater: 0,
        status: 'unreported' as const,
        isSupported: false,
      };
    });

    const totalWaterAll = +(totalApprovedWater + totalPendingWater + totalDraftWater).toFixed(2);
    totalApprovedWater = +totalApprovedWater.toFixed(2);
    totalPendingWater = +totalPendingWater.toFixed(2);
    totalDraftWater = +totalDraftWater.toFixed(2);
    surfaceWaterTotal = +surfaceWaterTotal.toFixed(2);
    groundwaterTotal = +groundwaterTotal.toFixed(2);
    unconventionalTotal = +unconventionalTotal.toFixed(2);

    const usageRatio = lic.annualQuota > 0 ? +((totalApprovedWater / lic.annualQuota) * 100).toFixed(1) : 0;

    let quotaAlertLevel: 'safe' | 'warning' | 'danger' = 'safe';
    if (usageRatio >= 100) {
      quotaAlertLevel = 'danger';
    } else if (usageRatio >= 80) {
      quotaAlertLevel = 'warning';
    }

    return {
      licenseId: lic.id,
      permitNumber: lic.permitNumber,
      licenseName: lic.licenseName,
      waterOwner: lic.waterOwner,
      district: lic.district,
      waterSourceType: lic.waterSourceType,
      industryType: lic.industryType,
      year,
      annualQuota: lic.annualQuota,
      totalApprovedWater,
      totalPendingWater,
      totalDraftWater,
      totalWaterAll,
      usageRatio,
      surfaceWaterTotal,
      groundwaterTotal,
      unconventionalTotal,
      quotaAlertLevel,
      reportedMonthsCount,
      approvedMonthsCount,
      monthlyBreakdown,
    };
  });
}
