export type AlarmOrderStatus = '待处置' | '工单处理中' | '待修订水量' | '待审核' | '工单处置完成';

export interface FaultRecord {
  id: string;
  facilityName: string; // 计量设施名称
  faultType: string; // 故障类型
  faultDesc: string; // 故障情况
  faultImage?: string; // 故障图片
  reporter: string; // 上报人
  faultTime: string; // 故障时间
  status: '待处理' | '处理中' | '已修复'; // 状态
  processStep?: string; // 流程
}

export interface AlarmWorkOrder {
  id: string;
  orderNo: string; // 单号 (如 202606260600281492)
  ticketNo?: string; // 兼容旧命名
  alarmBadge: '红色告警' | '蓝色告警' | '黄色告警'; // 告警标识
  createTime: string; // 工单生成时间 (如 2025-04-17 09:57)
  facilityName: string; // 计量设施名称
  facilityCode: string; // 计量设施编码 (如 632524JL00082)
  transmissionMode: '在线' | '非在线'; // 传输方式
  constructionSource: string; // 数据建设来源 (中央发展资金/自计量/国控水资源(监控)/省级发展基金/国控等)
  specialCase: string; // 特殊情形备案 (停用 / - / 检修 / 报废)
  recoverTime: string; // 恢复时间
  alarmCount: number; // 告警数量 (如 323)
  orderStatus: AlarmOrderStatus; // 工单状态: 待处置、工单处理中、待修订水量、待审核、工单处置完成
  timeoutStatus: '未超时' | '已超时'; // 超时情况
  timeoutDuration?: string; // 已超时时间 (如 '40天')
  disposalTimeRange?: string; // 工单处置时间 (如 '2026-06-26 08:00:00 至 2026-07-03 08:00:00')
  alarmTypeDesc?: string; // 告警类型 (如 '未上报,缺报')
  alarmContentDesc?: string; // 告警内容 (如 '未上报、系统自动补0;缺报、系统自动补空')
  monitorLevel?: '部级' | '省级' | '市级' | '县级'; // 监控级别
  district: string; // 所属区划 (西宁市/城东区/城中区/城西区/城北区/湟中区/大通县/湟源县/兴海县等)
  waterOwner?: string; // 取水权人
  assignee?: string;
  assignUnit?: string;
  feedback?: string;
  level?: '高危' | '紧急' | '一般';
  status?: string;
  title?: string;
  alarmType?: string;
  faultRecords?: FaultRecord[];
}

